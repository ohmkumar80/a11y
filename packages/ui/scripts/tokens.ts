// Run with Node >= 22.18 (native TypeScript stripping): node scripts/tokens.ts --check|--write
import { readFileSync, writeFileSync } from "node:fs";
import { colors, requiredPairs, type Theme } from "../src/tokens/tokens.ts";
import { contrastRatio } from "../src/tokens/contrast.ts";

const cssPath = new URL("../src/tokens.css", import.meta.url);

function block(theme: Theme): string {
  return Object.entries(colors[theme])
    .map(([k, v]) => `  --a11y-${k}: ${v};`)
    .join("\n");
}

const themeMap = Object.keys(colors.light)
  .map((k) => `  --color-${k}: var(--a11y-${k});`)
  .join("\n");

const generated = `/* GENERATED by scripts/tokens.ts from src/tokens/tokens.ts - do not edit. */
:root {
  color-scheme: light dark;
${block("light")}
}
:root[data-theme="dark"] {
  color-scheme: dark;
${block("dark")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block("dark").replace(/^/gm, "  ")}
  }
}
/* Expose tokens as Tailwind utilities (bg-bg, text-fg, border-border, ...). */
@theme inline {
${themeMap}
}
`;

if (process.argv.includes("--write")) {
  writeFileSync(cssPath, generated);
  console.log("wrote src/tokens.css");
  process.exit(0);
}

let failures = 0;
for (const theme of ["light", "dark"] as const) {
  for (const [fg, bg, min, why] of requiredPairs) {
    const ratio = contrastRatio(colors[theme][fg], colors[theme][bg]);
    const ok = ratio >= min;
    if (!ok) failures++;
    console.log(`${ok ? "PASS" : "FAIL"} [${theme}] ${fg} on ${bg}: ${ratio.toFixed(2)}:1 (needs ${min}) - ${why}`);
  }
}
let current = "";
try { current = readFileSync(cssPath, "utf8"); } catch { /* missing */ }
if (current !== generated) {
  failures++;
  console.log("FAIL src/tokens.css is out of date. Run: pnpm --filter @a11y/ui build:tokens");
}
if (failures) {
  console.error(`\n${failures} token check(s) failed`);
  process.exit(1);
}
console.log("\nAll token contrast checks passed");
